#ifndef __KEY_H
#define __KEY_H

#include "board.h"
#include <stdint.h>

/* ============================================================
 * 按键驱动 (纯扫描, 不含任务逻辑)
 *   K1 = PB27, K2 = PA25, K3 = PA26 (用户确认, 3 个独立按键, 无拨码)
 *   按键上拉, 按下读到低电平
 *
 * 接口:
 *   Key_GetNum() — 阻塞去抖, 返回当前按下键号 (0=无, 1/2/3=K1/K2/K3)
 *   Key_Scan()   — 非阻塞, 返回当前键号 (不去抖, 供中断态查询)
 *
 * 引脚宏由 syscfg KEY 实例生成 (GPIO_KEY_K1/K2/K3_PORT/PIN)
 * ============================================================ */

uint8_t Key_GetNum(void);   /* 阻塞去抖, 松开后返回键号 */
uint8_t Key_Scan(void);     /* 非阻塞, 即时返回键号 */

#endif /* __KEY_H */
